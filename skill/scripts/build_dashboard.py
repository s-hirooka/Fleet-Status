r"""Rebuild the Fleet Status dashboard HTML from whatever is currently in
D:\path\to\twi-autoV2\dashboard_data\ (each of the 4 scheduled tasks
updates its own slice there; this script just assembles the latest state of
all four into one HTML file, ready to be published with the Artifact tool).

This does NOT publish anything itself -- run it, then use the Artifact tool
to publish the resulting file to:
  <ARTIFACT_URL>
with capabilities {"db": {}}.

Usage:
    python build_dashboard.py
    -> writes D:\...\dashboard_data\dashboard_final.html
"""
import csv
import json
import os

DATA_DIR = r"D:\path\to\twi-autoV2\dashboard_data"
MAIL_OVERRIDES_PATH = r"D:\path\to\twi-autoV2\mail_overrides.json"
SCRIPTS_DIR = os.path.dirname(os.path.abspath(__file__))


def load_json(path, default=None):
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    return default


def load_read_handles():
    """Handles whose X lock/suspend notification email has been marked read in
    Gmail. Once the alert mail is read, the lock is treated as acknowledged and
    is hidden from BOTH the account table (mail_overrides fixed display) and the
    mail list. This file is regenerated by the fleet-mail-check task."""
    data = load_json(os.path.join(DATA_DIR, "mail_read_status.json"), {}) or {}
    return set(data.get("readHandles", []))


def build_report_csv():
    """Re-run build_report.py's logic in-process (accounts + results + overrides -> rows)."""
    accounts = load_json(os.path.join(DATA_DIR, "accounts_combined.json"), {})
    overrides = load_json(MAIL_OVERRIDES_PATH, {})
    read_handles = load_read_handles()
    overrides = {h: v for h, v in overrides.items() if h not in read_handles}

    # Load the previous full results as a fallback FIRST, then overlay the current
    # results on top. This matters because check_shadowban.py's daily full-recheck
    # renames the old (last known-good) file to .bak and starts writing a brand new
    # one from scratch -- if the checker site is down/degraded that day, the new
    # file only covers a handful of handles. Without this fallback, every handle
    # missing from today's run would show as "未チェック" in the published
    # dashboard, silently discarding yesterday's real judgements. (Seen in
    # practice on 2026-09-12 and 2026-09-13 when shadowban-api.yuzurisa.com was
    # returning mass HTTP 500s.) With the fallback, a handle keeps its last known
    # judgement until it is actually rechecked again.
    results = {}
    bak_path = os.path.join(DATA_DIR, "results_combined.jsonl.bak")
    if os.path.exists(bak_path):
        with open(bak_path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    rec = json.loads(line)
                except ValueError:
                    continue
                results[rec["handle"]] = rec

    # check_shadowban.py now runs in small batches every 30 min (--limit) and
    # keeps appending to this same file rather than starting fresh each day, so
    # a handle can appear on multiple lines here -- take them in file order so
    # the last (most recent) line per handle wins.
    results_path = os.path.join(DATA_DIR, "results_combined.jsonl")
    if os.path.exists(results_path):
        with open(results_path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    rec = json.loads(line)
                except ValueError:
                    continue
                # Only let a fresh entry overwrite the fallback if it's an actual
                # check result, not a transient API failure -- an "unreachable"
                # entry from today shouldn't blank out a real judgement from
                # yesterday.
                if rec.get("reachable", True) or rec["handle"] not in results:
                    results[rec["handle"]] = rec

    ADHOC = "(個別指定・元データ外)"
    all_handles = set(accounts.keys()) | set(results.keys()) | set(overrides.keys())
    rows = []
    for handle in sorted(all_handles):
        judgement, detail, checked_at = "未チェック", "", ""
        if handle in overrides:
            judgement = overrides[handle].get("judgement", judgement)
            detail = overrides[handle].get("detail", detail)
            checked_at = overrides[handle].get("checked_at", checked_at)
        elif handle in results:
            judgement = results[handle].get("judgement", judgement)
            detail = results[handle].get("detail", detail)
            checked_at = results[handle].get("checked_at", checked_at)

        entries = accounts.get(handle) or [{"url": f"https://x.com/{handle}", "display": "",
                                             "genre": "", "system": ADHOC}]
        for e in entries:
            rows.append({
                "handle": handle,
                "display": e.get("display", ""),
                "genre": e.get("genre", ""),
                "system": e.get("system", ADHOC),
                "judgement": judgement,
                "checked_at": checked_at,
                "detail": detail,
                "url": e.get("url", f"https://x.com/{handle}"),
            })
    rows.sort(key=lambda r: (r["system"], r["handle"]))
    return rows


def build_status(rows):
    total = len(rows)
    unchecked = sum(1 for r in rows if r["judgement"] == "未チェック")
    checked_ats = [r["checked_at"] for r in rows if r["checked_at"]]
    finished_at = max(checked_ats) if checked_ats else None
    return {
        "finishedAt": finished_at,
        "siteAvailable": True,
        "totalHandles": total,
        "checkedCount": total - unchecked,
        "uncheckedCount": unchecked,
    }


def build_backup_data():
    status = load_json(os.path.join(DATA_DIR, "backup_status.json"), {})
    trackings = load_json(os.path.join(DATA_DIR, "backup_trackings.json"), {})
    out = []
    for sysname, r in status.items():
        out.append({
            "system": sysname,
            "ok": r.get("ok"),
            "backedUpAt": r.get("backed_up_at"),
            "bytes": r.get("dest_bytes"),
            "rows": r.get("rows"),
            "error": r.get("error"),
            "trackings": trackings.get(sysname, []),
        })
    out.sort(key=lambda b: b["system"])
    return out


def main():
    rows = build_report_csv()
    data_json = json.dumps(rows, ensure_ascii=False)
    status_json = json.dumps(build_status(rows), ensure_ascii=False)

    read_handles = load_read_handles()
    mail_data = load_json(os.path.join(DATA_DIR, "mail_data.json"), {
        "account": "monitor@example.com", "lastCheckedAt": None, "records": []
    })
    # Drop mail-list entries whose alert mail has been read (acknowledged).
    mail_data["records"] = [r for r in mail_data.get("records", [])
                            if r.get("handle") not in read_handles]
    mail_json = json.dumps(mail_data, ensure_ascii=False)
    backup_json = json.dumps(build_backup_data(), ensure_ascii=False)
    amazon_json = json.dumps(load_json(os.path.join(DATA_DIR, "amazon_data.json"), {
        "rows": [], "dailyByTracking": {}, "accountCountByTracking": {},
        "monthlyTotalsByTracking": {}, "dailyAllTracking": [], "totalAccountCount": 0,
        "amazonPeriod": {"label": "", "start": "", "end": ""}, "amazonLastUpdated": None,
        "xClickUnsupportedSystems": [],
    }), ensure_ascii=False)

    with open(os.path.join(DATA_DIR, "template.html"), encoding="utf-8") as f:
        tmpl = f.read()

    out = (tmpl.replace("__DATA_JSON__", data_json)
                .replace("__STATUS_JSON__", status_json)
                .replace("__MAIL_JSON__", mail_json)
                .replace("__BACKUP_JSON__", backup_json)
                .replace("__AMAZON_JSON__", amazon_json))

    out_path = os.path.join(DATA_DIR, "dashboard_final.html")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(out)

    print(f"wrote {out_path} ({len(out.encode('utf-8'))} bytes)")
    print(f"accounts: {len(rows)}")


if __name__ == "__main__":
    main()
